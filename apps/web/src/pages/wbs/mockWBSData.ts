import { addDays } from 'date-fns';
import type { Activity, ActivityStatus, DependencyType } from '@/types/activity';
import { ActivityStatus as AS, DependencyType as DT } from '@/types/activity';

const baseDate = new Date('2025-01-01');

interface MockActivityInput {
  id: string;
  projectId: string;
  name: string;
  code: string;
  wbsNodeId: string;
  startOffset: number; // days from baseDate
  duration: number;
  status: ActivityStatus;
  percentComplete: number;
  isCritical: boolean;
  estimatedHours: number;
  predecessors?: Array<{ activityId: string; type: DependencyType; lagDays: number }>;
}

function createActivity(input: MockActivityInput): Activity {
  return {
    id: input.id,
    projectId: input.projectId,
    name: input.name,
    code: input.code,
    wbsNodeId: input.wbsNodeId,
    plannedStartDate: addDays(baseDate, input.startOffset).toISOString(),
    plannedEndDate: addDays(baseDate, input.startOffset + input.duration).toISOString(),
    durationDays: input.duration,
    status: input.status,
    percentComplete: input.percentComplete,
    isCritical: input.isCritical,
    assignedUserIds: [],
    assignedUserNames: [],
    estimatedHours: input.estimatedHours,
    actualHours: 0,
    plannedCost: 0,
    actualCost: 0,
    totalFloat: 0,
    freeFloat: 0,
    tags: [],
    predecessors: (input.predecessors || []).map(p => ({
      activityId: p.activityId,
      activityName: '', // Will be filled by the system
      type: p.type,
      lagDays: p.lagDays,
    })),
    successors: [],
    createdAt: new Date().toISOString(),
    updatedAt: new Date().toISOString(),
  };
}

